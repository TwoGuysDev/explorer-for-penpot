// Preview tab: draws the board (or the page) as SVG and, when the editor already generated one,
// offers Penpot's own thumbnail for comparison.
import * as vscode from "vscode";
import { PenpotApi, ROOT_ID } from "./api";
import { describeError, describeWarning } from "./messages";
import { renderSvg } from "./render";
import type { PenpotNode, PenpotTree } from "./tree";

interface Target {
  teamId: string;
  fileId: string;
  pageId: string;
  frameId?: string;
  title: string;
}

export class PreviewPanel {
  private static current: PreviewPanel | undefined;
  private target: Target | undefined;
  private api: PenpotApi | undefined;
  private readonly images = new Map<string, Promise<string | undefined>>();
  private readonly panel: vscode.WebviewPanel;

  static show(ctx: vscode.ExtensionContext, api: PenpotApi, tree: PenpotTree, node: PenpotNode) {
    const { teamId, fileId, pageId, frameId } = node.ids;
    if (!teamId || !fileId || !pageId) return;
    const title = typeof node.label === "string" ? node.label : node.label?.label || "Penpot";
    if (!PreviewPanel.current) PreviewPanel.current = new PreviewPanel(ctx, tree);
    void PreviewPanel.current.load(api, { teamId, fileId, pageId, frameId, title });
  }

  private constructor(ctx: vscode.ExtensionContext, private readonly tree: PenpotTree) {
    this.panel = vscode.window.createWebviewPanel("penpotExplorer.preview", "Penpot", vscode.ViewColumn.Active, {
      enableScripts: true,
      retainContextWhenHidden: true,
      localResourceRoots: [],
    });
    this.panel.iconPath = vscode.Uri.joinPath(ctx.extensionUri, "media", "penpot.svg");
    this.panel.onDidDispose(() => (PreviewPanel.current = undefined), null, ctx.subscriptions);
    this.panel.webview.onDidReceiveMessage(
      (msg) => {
        if (!this.target || !this.api) return;
        if (msg?.type === "open") {
          const t = this.target;
          void vscode.env.openExternal(vscode.Uri.parse(this.api.workspaceUrl(t.teamId, t.fileId, t.pageId, t.frameId)));
        } else if (msg?.type === "refresh") {
          this.images.clear();
          this.tree.refresh();
          void this.load(this.api, this.target);
        }
      },
      null,
      ctx.subscriptions,
    );
  }

  private loadImage = (mediaId: string, mime?: string) => {
    let p = this.images.get(mediaId);
    if (!p) {
      p = this.api!.fileMediaDataUri(mediaId, mime);
      this.images.set(mediaId, p);
    }
    return p;
  };

  private async load(api: PenpotApi, target: Target) {
    this.api = api;
    this.target = target;
    this.panel.title = target.title;
    this.panel.reveal(undefined, true);
    this.panel.webview.html = this.html(target, `<p class="msg">${escapeHtml(vscode.l10n.t("Loading…"))}</p>`, "");
    try {
      const objects = target.frameId
        ? (await api.getPage(target.fileId, target.pageId, target.frameId)).objects
        : await this.tree.pageObjects(api, target.fileId, target.pageId);
      const res = await renderSvg(objects, target.frameId || ROOT_ID, { loadImage: this.loadImage });
      let thumb = "";
      if (target.frameId) {
        const thumbs = await api.getThumbnails(target.fileId).catch(() => ({}) as Record<string, string>);
        const key = Object.keys(thumbs).find((k) => k.includes(`/${target.frameId}/`));
        thumb = (key && (await api.fetchDataUri(thumbs[key]))) || "";
      }
      if (this.target !== target) return; // another preview was requested meanwhile
      const notes = res.warnings.map(describeWarning);
      const info = `${Math.round(res.width)} × ${Math.round(res.height)}` + (notes.length ? ` · ${notes.join(", ")}` : "");
      this.panel.webview.html = this.html(target, res.svg, info, thumb);
    } catch (err) {
      if (this.target !== target) return;
      const msg = vscode.l10n.t("Could not load: {0}", describeError(err));
      this.panel.webview.html = this.html(target, `<p class="msg err">${escapeHtml(msg)}</p>`, "");
    }
  }

  private html(t: Target, svg: string, info: string, thumb = "") {
    const webFonts = vscode.workspace.getConfiguration("penpotExplorer").get<boolean>("preview.loadWebFonts", true);
    const nonce = Array.from({ length: 4 }, () => Math.random().toString(36).slice(2)).join("");
    const csp = [
      "default-src 'none'",
      "img-src data:",
      `style-src 'unsafe-inline'${webFonts ? " https://fonts.googleapis.com" : ""}`,
      webFonts ? "font-src https://fonts.gstatic.com" : "",
      `script-src 'nonce-${nonce}'`,
    ]
      .filter(Boolean)
      .join("; ");
    const L = {
      fit: vscode.l10n.t("Fit"),
      actual: vscode.l10n.t("100%"),
      fitTitle: vscode.l10n.t("Switch between fit to window and 100%"),
      thumb: vscode.l10n.t("Thumbnail"),
      thumbTitle: vscode.l10n.t("Compare with the thumbnail generated by the Penpot editor"),
      thumbAlt: vscode.l10n.t("Penpot thumbnail"),
      refresh: vscode.l10n.t("Refresh"),
      refreshTitle: vscode.l10n.t("Fetch again from Penpot"),
      open: vscode.l10n.t("Open in Penpot"),
      openTitle: vscode.l10n.t("Open this item in the Penpot editor"),
    };
    return `<!doctype html><html lang="${escapeHtml(vscode.env.language)}"><head><meta charset="utf-8">
<meta http-equiv="Content-Security-Policy" content="${csp}">
${webFonts ? `<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Inter:wght@100..900&family=JetBrains+Mono:wght@400;700&display=swap">` : ""}
<style>
  body { margin: 0; font: 13px var(--vscode-font-family); color: var(--vscode-foreground); background: var(--vscode-editor-background); }
  header { position: sticky; top: 0; z-index: 1; display: flex; gap: 8px; align-items: center; padding: 8px 12px;
    background: var(--vscode-editor-background); border-bottom: 1px solid var(--vscode-panel-border); }
  header h1 { font-size: 13px; margin: 0; flex: 1; overflow: hidden; text-overflow: ellipsis; white-space: nowrap; }
  header .info { opacity: .7; white-space: nowrap; overflow: hidden; text-overflow: ellipsis; }
  button { font: inherit; color: var(--vscode-button-secondaryForeground); background: var(--vscode-button-secondaryBackground);
    border: 0; border-radius: 4px; padding: 4px 10px; cursor: pointer; white-space: nowrap; }
  button:hover { background: var(--vscode-button-secondaryHoverBackground); }
  button:focus-visible { outline: 1px solid var(--vscode-focusBorder); outline-offset: 2px; }
  button[aria-pressed="true"] { color: var(--vscode-button-foreground); background: var(--vscode-button-background); }
  main { padding: 16px; overflow: auto; }
  .stage svg, .stage img { display: block; margin: 0 auto; box-shadow: 0 2px 12px rgba(0,0,0,.35); }
  .fit svg, .fit img { max-width: 100%; height: auto; }
  .msg { opacity: .8; } .err { color: var(--vscode-errorForeground); }
  [hidden] { display: none !important; }
</style></head><body>
<header>
  <h1 title="${escapeHtml(t.title)}">${escapeHtml(t.title)}</h1>
  <span class="info">${escapeHtml(info)}</span>
  <button id="zoom" aria-pressed="true" title="${escapeHtml(L.fitTitle)}">${escapeHtml(L.fit)}</button>
  ${thumb ? `<button id="thumb" aria-pressed="false" title="${escapeHtml(L.thumbTitle)}">${escapeHtml(L.thumb)}</button>` : ""}
  <button id="refresh" title="${escapeHtml(L.refreshTitle)}">${escapeHtml(L.refresh)}</button>
  <button id="open" title="${escapeHtml(L.openTitle)}">${escapeHtml(L.open)}</button>
</header>
<main class="stage fit" id="stage">
  <div id="render">${svg}</div>
  ${thumb ? `<div id="thumbView" hidden><img src="${thumb}" alt="${escapeHtml(L.thumbAlt)}"></div>` : ""}
</main>
<script nonce="${nonce}">
  const vscode = acquireVsCodeApi();
  const stage = document.getElementById('stage');
  const zoom = document.getElementById('zoom');
  const labels = ${JSON.stringify({ fit: L.fit, actual: L.actual })};
  zoom.onclick = () => { const fit = stage.classList.toggle('fit'); zoom.setAttribute('aria-pressed', String(fit)); zoom.textContent = fit ? labels.fit : labels.actual; };
  document.getElementById('open').onclick = () => vscode.postMessage({ type: 'open' });
  document.getElementById('refresh').onclick = () => vscode.postMessage({ type: 'refresh' });
  const thumb = document.getElementById('thumb');
  if (thumb) thumb.onclick = () => {
    const on = thumb.getAttribute('aria-pressed') !== 'true';
    thumb.setAttribute('aria-pressed', String(on));
    document.getElementById('render').hidden = on;
    document.getElementById('thumbView').hidden = !on;
  };
</script></body></html>`;
  }
}

function escapeHtml(s: string) {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}
